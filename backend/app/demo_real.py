"""Build a small REAL (non-demo) mohalla through the public API, with a SIMULATED history (30 days up to yesterday, plus today), then run a bulk plan.

    python -m app.demo_real            # build the mohalla, then print what every feature returned
    python -m app.demo_real --approve  # also approve the bulk plan and print the order

Uses only HTTP calls, exactly like the UI does. For the 6 shops (about 220 m apart) it sends:
  - an opening batch received 31 days ago, then daily sales from 30 days ago up to today, using the backdating
    fields (received_on on the batch, sold_on on each sale). Numbers come from app/demo_story.py (fixed seed).
    30 full days before today is what the XGBoost forecast needs, so the bulk plan can use it.
  - a sales spike on the last day at 4 shops, a sales drop at 1 shop, one overdue udhaar customer,
    and a near-expiry milk batch next to a shop that is nearly out of it.
  - one distributor with quotes, then a bulk plan.
At the end it prints what /api/pulse, /api/pulse/drops, /api/khata/drafts, /api/swaps/suggestions, /api/stock,
/api/prices/radar, /api/impact and the plan returned.

ALL history is SIMULATED by this script. It is not real merchant history, and WhatsApp reminders are simulated.

Safe to re-run: existing shops are logged in, not registered again. A product's story is judged from the units on
hand: nothing there -> it is built, exactly the opening quantity -> only the sales are posted, exactly the finished
amount -> skipped. Anything else (a half-finished run, or you used the app) is left alone with a warning. To start
over: python -m app.reset_demo --force  (wipes ALL data, including these shops), then run this again.
The history is dated from the day it was first built (the spike is on that day), so build it on the day you demo,
or start over if it is more than a day old. Quotes are refreshed and a new bulk plan is drawn on every run.

Tip: pooled demand gets Laplace noise. For a stable demo set DP_EPSILON=20 in .env and restart the backend.
"""
import os
import sys
from datetime import date, timedelta

import httpx

from app import demo_story as story
from app.demo_story import MILK, PRODUCTS, SHOP_NAMES

BASE = os.getenv("VISTAAR_API", "http://localhost:8000").rstrip("/")
PASSWORD = "vistaar123"
LAT, LNG, STEP = 28.6139, 77.2090, 0.002  # ~220 m between shops
SHOPS = SHOP_NAMES
DISTRIBUTOR = "Demo Real Wholesaler"
QUOTE_SHARE = 0.85  # quote price as a share of the selling price
QUOTE_MIN_QTY = 30

SIMULATED_NOTE = ("SIMULATED: the stock, sales and udhaar history above was generated by this script (seed "
                  f"{story.SEED}) and sent as backdated entries. It is not real merchant history. WhatsApp is simulated too.")


def phone(i: int) -> str:
    return f"91000000{i + 1:02d}"


def make_client() -> httpx.Client:
    return httpx.Client()


def call(client: httpx.Client, method: str, path: str, token: str | None = None, ok=(200, 201), **kw):
    headers = {"Authorization": f"Bearer {token}"} if token else {}
    r = client.request(method, BASE + path, headers=headers, timeout=30, **kw)
    if r.status_code not in ok:
        sys.exit(f"{method} {path} -> {r.status_code}: {r.text[:300]}")
    return r.json()


def get_session(client: httpx.Client, i: int) -> tuple[str, bool]:
    """Return (token, is_new). Logs in if the shop exists, otherwise registers it."""
    r = client.post(BASE + "/api/auth/login", json={"phone": phone(i), "password": PASSWORD}, timeout=30)
    if r.status_code == 200:
        return r.json()["token"], False
    body = {"phone": phone(i), "name": f"Owner {i + 1}", "password": PASSWORD, "shop_name": SHOPS[i],
            "area": "Demo Mohalla", "lat": LAT + i * STEP, "lng": LNG, "upi_vpa": ""}
    return call(client, "POST", "/api/auth/register", json=body)["token"], True


def units_on_hand(client: httpx.Client, token: str, name: str) -> int:
    return sum(r["qty_left"] for r in call(client, "GET", "/api/stock", token) if r["product"] == name)


def build_product(client, token, today, shop, name, category, sell, cost, opening, sales, final, *,
                  received_days_ago, expiry_in_days=None) -> str:
    """Create the opening batch and the backdated daily sales for one shop and product. Returns the state it found."""
    state = story.story_state(units_on_hand(client, token, name), opening, final)
    created = False
    if state == "absent":
        batch = {"product_name": name, "category": category, "qty": opening, "cost_price": cost, "sell_price": sell,
                 "received_on": str(today - timedelta(days=received_days_ago))}
        if expiry_in_days is not None:
            batch["expiry_date"] = str(today + timedelta(days=expiry_in_days))
        call(client, "POST", "/api/stock/batches", token, json=batch)
        created, state = True, "fresh"
    if state == "fresh":
        if not sales:  # a batch that is never sold from (the near-expiry milk): opening == final
            return "built" if created else "done"
        pid = call(client, "GET", "/api/products", token, params={"q": name})[0]["id"]
        for days_ago in sorted(sales, reverse=True):  # oldest day first
            call(client, "POST", "/api/sales", token, json={
                "product_id": pid, "qty": sales[days_ago], "sold_on": str(today - timedelta(days=days_ago))})
        return "built"
    if state == "changed":
        print(f"  WARNING: {SHOPS[shop]} / {name}: stock is not at the story's start or end "
              f"(half-finished run, or you used the app). Left alone. See 'start over' at the top of this file.")
    return state


def build_shop_history(client, tokens, today) -> dict:
    result = {}
    for i, token in enumerate(tokens):
        for name, category, sell, cost in PRODUCTS:
            result[(i, name)] = build_product(
                client, token, today, i, name, category, sell, cost, story.opening_qty(i, name),
                story.daily_sales(i, name), story.leftover(i, name), received_days_ago=story.OPENING_DAYS_AGO)

    # near-expiry long-life milk at the sender: nobody buys it, so most of it is at risk
    m_name, m_cat, m_sell, m_cost = MILK
    sender, receiver = story.MILK_SENDER, story.MILK_RECEIVER
    result[(sender, m_name)] = build_product(
        client, tokens[sender], today, sender, m_name, m_cat, m_sell, m_cost, story.MILK_SENDER_QTY, {},
        story.MILK_SENDER_QTY, received_days_ago=story.MILK_SENDER_RECEIVED_DAYS_AGO,
        expiry_in_days=story.MILK_EXPIRES_IN_DAYS)
    # the neighbour sells the same milk fast and is nearly out
    result[(receiver, m_name)] = build_product(
        client, tokens[receiver], today, receiver, m_name, m_cat, m_sell, m_cost, story.milk_receiver_opening_qty(),
        story.milk_receiver_sales(), story.MILK_RECEIVER_LEFT, received_days_ago=story.MILK_RECEIVER_DAYS - 1,
        expiry_in_days=story.MILK_RECEIVER_EXPIRES_IN_DAYS)
    return result


def build_udhaar(client, token, today) -> str:
    """One customer with credit entered 20 days ago and never paid, so a khata draft appears."""
    name, number = story.UDHAAR_CUSTOMER
    customers = call(client, "GET", "/api/udhaar/customers", token)
    card = next((c for c in customers if c["display_name"] == name), None)
    if card is None:
        card = call(client, "POST", "/api/udhaar/customers", token,
                    json={"name": name, "phone": number, "aliases": ["Ramesh bhai"]})
    if call(client, "GET", f"/api/udhaar/customers/{card['id']}", token)["recent"]:
        return "done"
    call(client, "POST", "/api/udhaar/entries", token, json={
        "customer_id": card["id"], "kind": "credit", "amount": story.UDHAAR_AMOUNT, "note": "demo udhaar (simulated)",
        "entry_date": str(today - timedelta(days=story.UDHAAR_DAYS_AGO))})
    return "built"


def add_distributor_quotes(client, boss) -> None:
    dists = call(client, "GET", "/api/distributors", boss)
    dist = next((d for d in dists if d["name"] == DISTRIBUTOR), None)
    if dist is None:
        dist = call(client, "POST", "/api/distributors", boss, json={"name": DISTRIBUTOR})
    valid_till = str(date.today() + timedelta(days=5))
    for name, _cat, sell, _cost in PRODUCTS:
        pid = call(client, "GET", "/api/products", boss, params={"q": name})[0]["id"]
        call(client, "POST", f"/api/distributors/{dist['id']}/quotes", boss, json={
            "product_id": pid, "unit_price": round(sell * QUOTE_SHARE, 2), "min_qty": QUOTE_MIN_QTY,
            "delivery_days": 2, "valid_till": valid_till})
    print(f"Distributor '{DISTRIBUTOR}' has quotes for {len(PRODUCTS)} products (valid till {valid_till}).")


def check_features(client, tokens) -> dict:
    """Call every feature endpoint the story is meant to light up, print the answers, and say which ones fired."""
    s = story
    pulse = call(client, "GET", "/api/pulse", tokens[s.UDHAAR_SHOP])
    drop = call(client, "GET", "/api/pulse/drops", tokens[s.DROP_SHOP])
    no_drop = call(client, "GET", "/api/pulse/drops", tokens[0])
    khata = call(client, "GET", "/api/khata/drafts", tokens[s.UDHAAR_SHOP])
    swaps_out = call(client, "GET", "/api/swaps/suggestions", tokens[s.MILK_SENDER])
    swaps_in = call(client, "GET", "/api/swaps/suggestions", tokens[s.MILK_RECEIVER])
    stock = call(client, "GET", "/api/stock", tokens[s.MILK_SENDER])
    radar = call(client, "GET", "/api/prices/radar", tokens[s.UDHAAR_SHOP])
    impact = call(client, "GET", "/api/impact", tokens[s.UDHAAR_SHOP])

    print("\n=== What each feature returned (history is SIMULATED) ===")
    print(f"\nPulse (GET /api/pulse as {SHOPS[s.UDHAAR_SHOP]}): {len(pulse['alerts'])} alert(s)")
    for a in pulse["alerts"]:
        print(f"  {a['product']}: {a['shops_spiking']} shops spiking, {a['uplift']}x, suggested +{a['suggested_qty']}")
        print(f"    {a['why']}")
    if pulse["message"]:
        print(f"  {pulse['message']}")

    print(f"\nSales drop (GET /api/pulse/drops as {SHOPS[s.DROP_SHOP]}): {drop['message']}")
    if drop["drop"]:
        d = drop["drop"]
        print(f"  down {d['drop_pct']}% (normal {d['baseline']}/day, last {d['recent_days']} days {d['recent']}/day), "
              f"{drop['days_of_data']} days of data, through {drop['through']}")
    print(f"  For contrast, {SHOPS[0]}: {no_drop['message']}")

    print(f"\nKhata drafts (GET /api/khata/drafts as {SHOPS[s.UDHAAR_SHOP]}): {len(khata)} draft(s)")
    for k in khata:
        print(f"  {k['display_name']}: Rs {k['pending']:.0f} pending, {k['overdue_days']} days. Not sent: you approve first.")
        print("    " + k["message"].replace("\n", "\n    "))

    print("\nSwap suggestions (GET /api/swaps/suggestions)")
    for label, res in ((f"as {SHOPS[s.MILK_SENDER]}", swaps_out), (f"as {SHOPS[s.MILK_RECEIVER]}", swaps_in)):
        print(f"  {label}: {len(res['proposals'])} proposal(s)" + (f" ({res['message']})" if res["message"] else ""))
        for p in res["proposals"]:
            print(f"    [{p['role']}] {p['qty']} x {p['product']}: {p['from_shop']} -> {p['to_shop']}, score {p['score']}")
            print(f"      {p['why']}")

    milk = [r for r in stock if r["product"] == MILK[0]]
    print(f"\nStock (GET /api/stock as {SHOPS[s.MILK_SENDER]}): {len(stock)} batches"
          + "".join(f"; {r['product']}: {r['qty_left']} left, risk {r['risk']['level']}" for r in milk))
    print(f"Price radar (GET /api/prices/radar): {len(radar)} product(s) with quotes")
    print(f"Impact (GET /api/impact): pool {impact['pool']['shops']} shops, basis '{impact['pool']['basis']}'; "
          f"simulated flag = {impact['simulated']} (real shops report False, but this history is still simulated)")

    checks = {
        "pulse spike": any(a["product"] == s.SPIKE_PRODUCT and a["shops_spiking"] >= 4 for a in pulse["alerts"]),
        "sales drop": drop["drop"] is not None and drop["days_of_data"] >= 17,
        "khata draft": any(k["display_name"] == s.UDHAAR_CUSTOMER[0] for k in khata),
        "swap suggestion": any(p["role"] == "send" and p["product"] == MILK[0] for p in swaps_out["proposals"]),
    }
    print("\nIs it live?  " + "   ".join(f"{k}: {'YES' if v else 'NOT SEEN'}" for k, v in checks.items()))
    if not all(checks.values()):
        print("Not everything fired. The history is dated from the day it was first built, so a spike or drop goes stale "
              "a day later,\nand a half-built or edited shop is left alone. Start over: python -m app.reset_demo --force, "
              "then run this again.")
    return {"checks": checks, "pulse": pulse, "drop": drop, "no_drop": no_drop, "khata": khata,
            "swaps_out": swaps_out, "swaps_in": swaps_in, "stock": stock, "radar": radar, "impact": impact}


def main(approve: bool = False) -> dict:
    today = date.today()
    with make_client() as client:
        tokens, new = [], []
        for i in range(len(SHOPS)):
            token, is_new = get_session(client, i)
            tokens.append(token)
            new.append(is_new)
        print(f"{sum(new)} new shop(s), {len(SHOPS) - sum(new)} existing.")
        print("Building the SIMULATED history through the API (this sends a few hundred requests)...")

        states = build_shop_history(client, tokens, today)
        udhaar_state = build_udhaar(client, tokens[story.UDHAAR_SHOP], today)
        counts = {k: sum(1 for v in states.values() if v == k) for k in ("built", "done", "changed")}
        print(f"Stock and sales: {counts['built']} built, {counts['done']} already there, {counts['changed']} left alone. "
              f"Udhaar customer: {udhaar_state}.")

        add_distributor_quotes(client, tokens[0])  # one distributor (added by shop 1) serves the whole real mohalla

        plan = call(client, "POST", "/api/orders/plan", tokens[1])
        print(f"\nPlan for {SHOPS[1]}: cohort {plan['cohort_size']} shops, status {plan['status']}")
        if not plan["lines"]:
            print("No lines in the plan. Pooled demand is noisy: set DP_EPSILON=20 in .env, restart, and re-run.")
        for ln in plan["lines"]:
            print(f"  {ln.get('product', ln['product_id'])}: my qty {ln['my_qty']} @ Rs {ln['unit_price']}"
                  f"  (saving Rs {ln['my_saving']})")
        print(f"Forecast method: {plan.get('forecast_method', 'unknown')}")
        for ln in plan["lines"]:
            if ln.get("reason"):
                print(f"  why {ln.get('product', ln['product_id'])}: {ln['reason']}")
        print(f"Estimated saving: Rs {plan['savings_estimate']}  [{plan['savings_basis']}]")
        if approve and plan["lines"]:
            done = call(client, "POST", f"/api/orders/{plan['thread_id']}/approve", tokens[1])
            print(f"Approved: orders {done['order_ids']}, audit hash {done['audit_hash'][:16]}...")

        results = check_features(client, tokens)
        results["plan"] = plan

        print(f"\nLog in to the UI with password {PASSWORD}:")
        print(f"  {phone(story.UDHAAR_SHOP)}  {SHOPS[story.UDHAAR_SHOP]}: pulse spike, khata draft, swap (sender), bulk plan")
        print(f"  {phone(story.MILK_RECEIVER)}  {SHOPS[story.MILK_RECEIVER]}: swap (receiver, approves it)")
        print(f"  {phone(story.DROP_SHOP)}  {SHOPS[story.DROP_SHOP]}: sales-drop alert")
        print("\n" + SIMULATED_NOTE)
        return results


if __name__ == "__main__":
    out = main(approve="--approve" in sys.argv)
    sys.exit(0 if all(out["checks"].values()) else 1)